import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import vm from 'node:vm';
import ts from 'typescript';
const calls=[];
const exported={};
const code=ts.transpileModule(await readFile('src/lib/analytics-transport.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
vm.runInNewContext(code,{exports:exported,AbortController,fetch:(url,options)=>{calls.push({url,options});return Promise.resolve({status:503});}});
const transport=exported.privacyTransport();
let permitted=true;
transport.send('https://collector.example','fixture',{event:'$pageview',properties:{token:'fixture'}},()=>permitted);
transport.send('https://collector.example','fixture',{event:'$snapshot',properties:{token:'fixture'}},()=>permitted);
assert.equal(calls.length,2);
assert(calls[1].url.endsWith('/s/?ip=0'));
assert.equal(calls[0].options.referrerPolicy,'no-referrer');
assert.equal(calls[0].options.credentials,'omit');
assert.equal(calls[0].options.keepalive,false);
permitted=false;transport.cancel();
assert(calls.every(c=>c.options.signal.aborted));
transport.send('https://collector.example','fixture',{event:'$$heatmap',properties:{}},()=>permitted);
await new Promise(resolve=>setTimeout(resolve,25));
assert.equal(calls.length,2,'503 must never enqueue or retry, nor send after withdrawal');
console.log('PASS one-shot 503 transport, independent abort, no retry, no beacon, no referrer, no credentials, post-withdrawal veto.');
